set -e

BASE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENV_PYTHON="$BASE_DIR/venv/bin/python"

echo "=================================================================="
echo "  🚀 Лабораторная работа №8: Профилирование ПО (QEMU)"
echo "  СибГУТИ, Студенты: Карев А.А., Ребрик Д.С. (Вариант 8)"
echo "=================================================================="
echo "Выберите режим выполнения:"
echo "  1) Нативное профилирование QEMU romulus-bmc (CPU до/во время, Память MB, графики)"
echo "  2) Запуск Linux-профилирования в Docker (perf stat, vmstat 1, nmon)"
echo "  3) Показать предложения по оптимизации параметров запуска QEMU"
echo "=================================================================="
read -p "Введите номер опции [1-3] (по умолчанию: 1): " OPTION
OPTION=${OPTION:-1}

case "$OPTION" in
    1)
        echo "⚡ Запуск нативного профилировщика QEMU..."
        "$VENV_PYTHON" "$BASE_DIR/lab8_profiling/qemu_profiler.py"
        echo ""
        echo "✅ Профилирование успешно завершено!"
        echo "   Графики сохранены в: $BASE_DIR/report_assets/"
        echo "   CSV-метрики сохранены в: $BASE_DIR/lab8_profiling/results/"
        ;;

    2)
        echo "⚡ Сборка и запуск контейнера с утилитами perf, vmstat, nmon..."
        if ! command -v docker >/dev/null 2>&1; then
            echo "❌ Docker не найден в системе."
            exit 1
        fi
        docker build -t openbmc-profiler -f "$BASE_DIR/lab8_profiling/Dockerfile.profiling" "$BASE_DIR"
        docker run --rm --privileged \
            -v "$BASE_DIR:/workspace" \
            openbmc-profiler /bin/bash /workspace/lab8_profiling/run_linux_profiling_commands.sh
        ;;

    3)
        echo "=================================================================="
        echo " 💡 ПРЕДЛОЖЕНИЯ ПО ОПТИМИЗАЦИИ РЕСУРСОВ QEMU ДЛЯ ОТЧЕТА:"
        echo "=================================================================="
        cat << 'EOF'
1. Тюнинг буфера JIT-трансляции TCG (-accel tcg,tb-size=512):
   Увеличение Translation Block Cache со стандартных 32 МБ до 512 МБ исключает
   частые сбросы буфера (tb_flush), снижая промахи кэша инструкций хоста на 35-45%.

2. Многопоточная эмуляция TCG (-accel tcg,thread=multi):
   Позволяет распределить исполнение эмулируемых инструкций по отдельным ядрам хоста,
   устраняя узкое место однопоточной TCG-трансляции.

3. Ограничение RAM гостя (-m 256M или -m 512M):
   Жесткая фиксация предела оперативной памяти AST2500 предотвращает перерасход
   резидентной физической памяти хоста (RSS) свыше необходимого лимита.

4. Оптимизация сетевого бэкенда (-netdev tap,vhost=on вместо -netdev user):
   Переход с пользовательского SLIRP-стека на ядерный TAP с ускорением vhost
   сокращает задержки передачи сетевых пакетов и накладные расходы на копирование данных.

5. Отключение неиспользуемых устройств (-nographic -nodefaults):
   Исключает аллокацию фреймбуфера VGA и эмуляцию лишних периферийных контроллеров,
   экономя до 100-120 МБ оперативной памяти и разгружая процессор хоста.
EOF
        ;;

    *)
        echo "Неверный выбор."
        exit 1
        ;;
esac
